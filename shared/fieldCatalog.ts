export type FieldType =
  | 'readonly_timestamp'
  | 'readonly_computed'
  | 'text'
  | 'phone'
  | 'email'
  | 'date'
  | 'time'
  | 'dropdown'
  | 'dependent_dropdown'
  | 'document' // an uploaded file (or a legacy 1/Done flag from old data)
  | 'money'
  | 'percentage';

export interface FieldDefinition {
  index: number; // 1 to 82 (62+ were added later and are appended so existing sheet columns keep their position)
  key: string;
  label: string;
  excelHeader: string;
  aliases?: string[];
  sectionId: number;
  type: FieldType;
  required?: boolean;
  /** Required when a NEW candidate is entered by hand; not enforced for legacy rows (import, edits of old rows). */
  requiredOnCreate?: boolean;
  dropdownListKey?: string;
  dependsOn?: string; // e.g., 'region' for 'location', 'location' for 'site'
  pinned?: boolean;
  /** Name of the document used in the uploaded file name (type 'document'). */
  docName?: string;
  width?: number;
  description?: string;
  /** Removed from forms, detail view and column lists. The column and its data stay (reports, imports, history). */
  hidden?: boolean;
  /** Text typed over several lines (textarea), no character limit. */
  multiline?: boolean;
  /** Only applies to ranks at this level or above: rank 3x and 4x are "up" of 4 (a smaller number = a higher rank). */
  maxRankNumber?: number;
}

