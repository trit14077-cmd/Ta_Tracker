/** "4A" -> 4, "3B" -> 3; NaN when the rank is empty or not a number. */
export function rankNumber(rank: string | null | undefined): number {
  const m = /^\s*(\d+)/.exec(String(rank || ''));
  return m ? Number(m[1]) : NaN;
}

/** False when the field is hidden or only applies to a higher rank than the candidate's. An unknown rank shows the field. */
export function isFieldApplicable(f: FieldDefinition, values: Record<string, unknown>): boolean {
  if (f.hidden) return false;
  if (f.maxRankNumber !== undefined) {
    const n = rankNumber(String(values.rank ?? ''));
    if (!Number.isNaN(n) && n > f.maxRankNumber) return false;
  }
  return true;
}
